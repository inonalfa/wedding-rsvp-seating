const draft = '<p class="alert info" role="note">טיוטה: הנוסח טרם עבר בדיקה משפטית ועשוי להשתנות.</p>';

function contact(email: string | undefined) {
  return email && /^[^\s@<>"]+@[^\s@<>"]+\.[^\s@<>"]+$/.test(email)
    ? `<a href="mailto:${escapeHtml(email)}" dir="ltr">${escapeHtml(email)}</a>`
    : "כתובת הפנייה תפורסם כאן לפני פתיחת השירות";
}

